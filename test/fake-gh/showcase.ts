/** A file's text at the base (0) or after commit `n` (1–3). */
export function showcaseFile(path: string, n: number): string | undefined {
	let content = SHOWCASE_BASE[path];
	for (const c of SHOWCASE_COMMITS.slice(0, n)) {
		for (const [from, to] of Object.entries(c.rename ?? {})) {
			if (to === path) content = SHOWCASE_BASE[from];
			if (from === path) content = undefined;
		}
		if (c.delete?.includes(path)) content = undefined;
		if (c.files[path] !== undefined) content = c.files[path];
	}
	return content;
}

/**
 * The 1-based line of `path` (after commit `n`; 0 is the base) that
 * contains `needle`, which must occur once.
 */
export function lineOf(path: string, n: number, needle: string): number {
	const lines = (showcaseFile(path, n) ?? "").split("\n");
	const found = lines.flatMap((l, i) => (l.includes(needle) ? [i + 1] : []));
	if (found.length !== 1) {
		throw new Error(`${path}@${n}: "${needle}" found ${found.length} times`);
	}
	return found[0] ?? 0;
}
