/** A solid `size`×`size` RGB PNG of colour `rgb`. */
export function png(rgb: [number, number, number], size = 8): Uint8Array {
	const chunk = (type: string, data: Buffer) => {
		const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
		const len = Buffer.alloc(4);
		len.writeUInt32BE(data.length);
		const crc = Buffer.alloc(4);
		crc.writeUInt32BE(crc32(body));
		return Buffer.concat([len, body, crc]);
	};
	const header = Buffer.alloc(13);
	header.writeUInt32BE(size, 0);
	header.writeUInt32BE(size, 4);
	header.set([8, 2, 0, 0, 0], 8);
	const row = Buffer.from([
		0,
		...Array.from({ length: size }, () => rgb).flat(),
	]);
	const pixels = Buffer.concat(Array.from({ length: size }, () => row));
	return Buffer.concat([
		Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
		chunk("IHDR", header),
		chunk("IDAT", deflateSync(pixels)),
		chunk("IEND", Buffer.alloc(0)),
	]);
}

/** The generated catalog: 400 lines, `edit` changing some entries. */
function catalog(edit: (i: number, line: string) => string = (_, l) => l) {
	const rows = Array.from({ length: 390 }, (_, k) => {
		const i = k + 1;
		const id = String(i).padStart(3, "0");
		const price = 499 + ((i * 37) % 50) * 100;
		return edit(
			i,
			`\t{ id: "w-${id}", name: "Widget ${id}", priceCents: ${price}, stock: ${(i * 13) % 97} },`,
		);
	});
	return text(
		"// Generated by scripts/catalog.mjs from catalog.csv. Do not edit.",
		"",
		'import type { Widget } from "../widgets/render";',
		"",
		"export const CATALOG: Widget[] = [",
		...rows,
		"];",
		"",
		"export const CATALOG_SIZE = CATALOG.length;",
	);
}

