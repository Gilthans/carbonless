#!/usr/bin/env bash
# Gallery case `rr-append`: commits appended after a review (shape S1).
# PS1 is reviewed in full (one cluster crossed off as generated); push 2
# inserts lines above a reviewed cluster (carried, P1), edits one (reworked,
# P3), grows one by an insertion inside it (P4), edits one of two identical
# clusters (P12: the other carries), regenerates the crossed-off file (P7:
# not carried) and adds a new cluster. See README.md here.
#
#   source .envrc && pnpm build && crb serve … &   (CLAUDE.md, "Branch instance")
#   scripts/gallery/rr-append.sh
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
CASE=rr-append

# ---- the files ---------------------------------------------------------------

write_base() {
	mkdir -p src/gen
	cat >src/relay.ts <<'EOF'
import { Target } from "./target";
import { log } from "./util";

export interface Delivery {
  id: string;
  target: Target;
  body: string;
}

export async function deliver(d: Delivery): Promise<boolean> {
  const res = await fetch(d.target.url, { method: "POST", body: d.body });
  log(`delivered ${d.id}: ${res.status}`);
  return res.ok;
}

export function headersFor(target: Target): Record<string, string> {
  const headers: Record<string, string> = {};
  headers["content-type"] = "application/json";
  headers["user-agent"] = "notify/1.4";
  return headers;
}

export function signature(body: string, secret: string): string {
  let h = 0;
  for (const c of body) h = (h * 31 + c.charCodeAt(0)) | 0;
  return `${secret.length}-${h}`;
}

export function validateTarget(target: Target): string[] {
  const problems: string[] = [];
  if (!target.url.startsWith("https://")) problems.push("url must be https");
  if (target.url.length > 2048) problems.push("url too long");
  return problems;
}

export function validateBody(body: string): string[] {
  const problems: string[] = [];
  if (body.length === 0) problems.push("body is empty");
  if (body.length > 65536) problems.push("body too long");
  return problems;
}

export function enqueue(queue: Delivery[], d: Delivery): number {
  queue.push(d);
  return queue.length;
}

export function dequeue(queue: Delivery[]): Delivery | undefined {
  return queue.shift();
}
EOF
	cat >src/util.ts <<'EOF'
export function log(line: string): void {
  console.log(line);
}
EOF
	cat >src/gen/api.g.ts <<'EOF'
// generated by notify-gen 1.4 — do not edit
export const VERSION = "1.4";
export const ROUTES = ["deliver"];
EOF
	cat >README.md <<'EOF'
# notify

Delivers webhooks to targets. `src/gen` is generated by `notify-gen`.
EOF
}

# PS1: retries, a user agent bump, a duplicate guard in both validators, a
# queue that logs and dedupes, the generated file regenerated, a helper.
write_push1() {
	cat >src/relay.ts <<'EOF'
import { Target } from "./target";
import { log } from "./util";

export interface Delivery {
  id: string;
  target: Target;
  body: string;
}

export async function deliver(d: Delivery): Promise<boolean> {
  let res = await fetch(d.target.url, { method: "POST", body: d.body });
  if (res.status >= 500) res = await fetch(d.target.url, { method: "POST", body: d.body });
  log(`delivered ${d.id}: ${res.status}`);
  return res.ok;
}

export function headersFor(target: Target): Record<string, string> {
  const headers: Record<string, string> = {};
  headers["content-type"] = "application/json";
  headers["user-agent"] = "notify/1.5";
  return headers;
}

export function signature(body: string, secret: string): string {
  let h = 0;
  for (const c of body) h = (h * 31 + c.charCodeAt(0)) | 0;
  return `${secret.length}-${h}`;
}

export function validateTarget(target: Target): string[] {
  const problems: string[] = [];
  if (!target.url.startsWith("https://")) problems.push("url must be https");
  if (target.url.length > 2048) problems.push("url too long");
  if (problems.length > 3) return problems.slice(0, 3);
  return problems;
}

export function validateBody(body: string): string[] {
  const problems: string[] = [];
  if (body.length === 0) problems.push("body is empty");
  if (body.length > 65536) problems.push("body too long");
  if (problems.length > 3) return problems.slice(0, 3);
  return problems;
}

export function enqueue(queue: Delivery[], d: Delivery): number {
  if (queue.some((q) => q.id === d.id)) return queue.length;
  queue.push(d);
  log(`queued ${d.id}`);
  return queue.length;
}

export function dequeue(queue: Delivery[]): Delivery | undefined {
  return queue.shift();
}
EOF
	cat >src/util.ts <<'EOF'
export function log(line: string): void {
  console.log(line);
}

export function now(): string {
  return new Date().toISOString();
}
EOF
	cat >src/gen/api.g.ts <<'EOF'
// generated by notify-gen 1.5 — do not edit
export const VERSION = "1.5";
export const ROUTES = ["deliver", "retry"];
EOF
}

# Push 2 (after the review): imports above the retry (it moves, unchanged),
# the user agent reworked, the queue's cluster grown by a line inside it,
# the second validator's guard edited (the first stays), the generated file
# regenerated again, and a new helper.
write_push2() {
	cat >src/relay.ts <<'EOF'
import { Target } from "./target";
import { log, now, retryAfter } from "./util";

const MAX_TRIES = 3;

export interface Delivery {
  id: string;
  target: Target;
  body: string;
}

export async function deliver(d: Delivery): Promise<boolean> {
  let res = await fetch(d.target.url, { method: "POST", body: d.body });
  if (res.status >= 500) res = await fetch(d.target.url, { method: "POST", body: d.body });
  log(`delivered ${d.id}: ${res.status}`);
  return res.ok;
}

export function headersFor(target: Target): Record<string, string> {
  const headers: Record<string, string> = {};
  headers["content-type"] = "application/json";
  headers["user-agent"] = `notify/1.5 (max ${MAX_TRIES} tries)`;
  return headers;
}

export function signature(body: string, secret: string): string {
  let h = 0;
  for (const c of body) h = (h * 31 + c.charCodeAt(0)) | 0;
  return `${secret.length}-${h}`;
}

export function validateTarget(target: Target): string[] {
  const problems: string[] = [];
  if (!target.url.startsWith("https://")) problems.push("url must be https");
  if (target.url.length > 2048) problems.push("url too long");
  if (problems.length > 3) return problems.slice(0, 3);
  return problems;
}

export function validateBody(body: string): string[] {
  const problems: string[] = [];
  if (body.length === 0) problems.push("body is empty");
  if (body.length > 65536) problems.push("body too long");
  if (problems.length > 2) return problems.slice(0, 2);
  return problems;
}

export function enqueue(queue: Delivery[], d: Delivery): number {
  if (queue.some((q) => q.id === d.id)) return queue.length;
  queue.push(d);
  d.target.lastQueued = now();
  log(`queued ${d.id}`);
  return queue.length;
}

export function dequeue(queue: Delivery[]): Delivery | undefined {
  return queue.shift();
}
EOF
	cat >src/util.ts <<'EOF'
export function log(line: string): void {
  console.log(line);
}

export function now(): string {
  return new Date().toISOString();
}

export function retryAfter(status: number): number {
  return status === 429 ? 1000 : 250;
}
EOF
	cat >src/gen/api.g.ts <<'EOF'
// generated by notify-gen 1.5.1 — do not edit
export const VERSION = "1.5.1";
export const ROUTES = ["deliver", "retry", "status"];
EOF
}

# ---- the branches and the PR --------------------------------------------------

gallery_clone
case_branches_start "$CASE"
(cd "$CLONE" && write_base)
commit_all "notify 1.4" >/dev/null
push_branch "base/$CASE"
g checkout --quiet -b "case/$CASE"
(cd "$CLONE" && write_push1)
PS1="$(commit_all "Retry failed deliveries once, dedupe the queue")"
push_branch "case/$CASE"

PR="$(open_pr "$CASE" "rr-append: commits appended after a review (carried, reworked, new)" <<'EOF'
Commits appended after the review (shape S1): the second push changes some of what was reviewed and leaves the rest alone. Open it in carbonless with PS1 reviewed (the seeding script does that), then view the head.

What happened, in order:

1. PS1 (`Retry failed deliveries once, dedupe the queue`): six clusters over `src/relay.ts`, `src/util.ts` and the generated `src/gen/api.g.ts`. The reviewer marks every cluster reviewed, crossing the generated file off as `generated`, and comments on the retry.
2. Push 2 (`Address review`): imports and a constant inserted above the retry, the user agent reworked, a line added inside the queue's cluster, the second validator's guard edited, the generated file regenerated, a new helper in `src/util.ts`.

| Cluster (PS1) | Push 2 | In carbonless, viewing the head since PS1 |
| --- | --- | --- |
| `deliver`: the retry (`relay.ts` 11–12) | three lines inserted above it, the cluster untouched | carried (P1): not in the since view, green with a `carried` chip in the full diff |
| `headersFor`: the user agent | edited again | `reworked` (P3): its old line red, the new one green |
| `validateTarget`: the guard | untouched | carried, though identical to the guard below (P12: duplicates pair by position, not by text) |
| `validateBody`: the same guard | edited (`> 2`) | the edited guard is `new` and the reviewed one is `gone` (a red block): two identical clusters only pair while both are there unchanged |
| `enqueue`: the dedupe line | untouched | carried |
| `enqueue`: the `log` line | a line added right before it | `reworked` (P4): the cluster grew, nothing of it carries |
| `api.g.ts`: regenerated, crossed off | regenerated again | `reworked` (P7): a crossed-off cluster never carries to different content |
| `util.ts`: `now()` | `retryAfter()` added right after it (one cluster now) | `reworked`: the reviewed addition is part of a bigger one |
| `relay.ts`: the imports and `MAX_TRIES` | new | `new` |

Look at: the patch set graph (PS1, then the head with `1 commit`; the connector's card says `1 new commit · 3 files, 6 clusters to read`), the toast on open, the since view against the full diff (Ctrl+Shift+[ moves the comparison base to the branch), the progress bar's `to read`, the tree's dots and the `needs eyes` filter, and that the first mark on the head starts PS2 with the carries (the rail gains PS2 and says up to date).

🤖 Generated with [Claude Code](https://claude.com/claude-code)
EOF
)"

# ---- the reviewer's part: PS1 ----------------------------------------------------

crb_open "$PR"
view="$(review_view)"
rev="$(jq -r .revision <<<"$view")"
[ "$(jq -r '.files | length' <<<"$view")" = 3 ] || die "expected 3 files on PS1"
relay=()
while IFS= read -r k; do relay+=("$k"); done < <(keys_of src/relay.ts <<<"$view")
util=()
while IFS= read -r k; do util+=("$k"); done < <(keys_of src/util.ts <<<"$view")
gen=()
while IFS= read -r k; do gen+=("$k"); done < <(keys_of src/gen/api.g.ts <<<"$view")
mark "$rev" reviewed -- "${relay[@]}" "${util[@]}"
mark "$rev" crossed-off generated -- "${gen[@]}"
comment "$PS1" src/relay.ts RIGHT 12 "Retrying once is not enough for a 503 that lasts: back off and try up to three times?"
log "PS1 reviewed: $(review_view | jq -c .progress.clusters)"

# ---- push 2 ---------------------------------------------------------------------

(cd "$CLONE" && write_push2)
PS2="$(commit_all "Address review: back off, dedupe by target, regenerate")"
push_branch "case/$CASE"
log "pushed $PS2; waiting for the server to see it"
wait_head "$PS2"
log "done: open $REVIEW_URL/files?key=$REVIEW_KEY and view the head"
