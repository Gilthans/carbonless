#!/usr/bin/env node
/**
 * Generates src/web/code/joiningTypes.ts: the code points whose Unicode
 * Joining_Type is D, R or L (everything else is unknown to the classifier,
 * so a ZWNJ next to it is escaped), and the scripts those letters belong to.
 *
 *   node scripts/gen-joining-types.mjs [DerivedJoiningType.txt] && pnpm fix
 *
 * Without a path it downloads the pinned version from unicode.org (dev time
 * only; nothing is fetched at runtime). Pin UNICODE to the Unicode version
 * of the Node that runs the app (`process.versions.unicode`; 17.0 for
 * Node 24.22), since the classifier's \p{Script} tests come from it. A table
 * older than Node's fails closed; a newer one fails a test.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const UNICODE = "17.0.0";
const URL = `https://www.unicode.org/Public/${UNICODE}/ucd/extracted/DerivedJoiningType.txt`;
const OUT = join(
	dirname(fileURLToPath(import.meta.url)),
	"../src/web/code/joiningTypes.ts",
);

const source = process.argv[2]
	? readFileSync(process.argv[2], "utf8")
	: await (await fetch(URL)).text();
if (!source.includes(`DerivedJoiningType-${UNICODE}.txt`)) {
	throw new Error(`not DerivedJoiningType-${UNICODE}.txt`);
}

/** [lo, hi, type] for D, R and L, merged where adjacent. */
const ranges = [];
for (const line of source.split("\n")) {
	const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([DRL])\b/.exec(line);
	if (!m) continue;
	const lo = Number.parseInt(m[1], 16);
	const hi = Number.parseInt(m[2] ?? m[1], 16);
	ranges.push([lo, hi, m[3]]);
}
ranges.sort((a, b) => a[0] - b[0]);
const merged = [];
for (const r of ranges) {
	const last = merged[merged.length - 1];
	if (last && last[2] === r[2] && last[1] + 1 === r[0]) last[1] = r[1];
	else merged.push([...r]);
}

// The scripts of those letters, as Node's own Script property names them.
const SCRIPTS = [
	"Adlam",
	"Arabic",
	"Chorasmian",
	"Hanifi_Rohingya",
	"Manichaean",
	"Mandaic",
	"Mongolian",
	"Nko",
	"Old_Uyghur",
	"Phags_Pa",
	"Psalter_Pahlavi",
	"Sogdian",
	"Syriac",
	"Common",
];
const scripts = new Set();
for (const [lo, hi] of merged) {
	for (let cp = lo; cp <= hi; cp++) {
		const ch = String.fromCodePoint(cp);
		const script = SCRIPTS.find((s) =>
			new RegExp(`^\\p{Script=${s}}$`, "u").test(ch),
		);
		if (!script) {
			throw new Error(`U+${cp.toString(16)}: script not in SCRIPTS`);
		}
		scripts.add(script);
	}
}
scripts.delete("Common");

const hex = (n) => `0x${n.toString(16)}`;
const out = `// Generated by scripts/gen-joining-types.mjs from Unicode ${UNICODE}
// DerivedJoiningType.txt. Do not edit by hand.

/** The Unicode version the table comes from. */
export const JOINING_UNICODE = "${UNICODE}";

/** Joining_Type D (dual), R (right) or L (left); others are not listed. */
export type JoiningType = "D" | "R" | "L";

/** Sorted, non-overlapping [first, last, type] code point ranges. */
export const JOINING_TYPES: readonly (readonly [number, number, JoiningType])[] = [
${merged.map(([lo, hi, t]) => `\t[${hex(lo)}, ${hex(hi)}, "${t}"],`).join("\n")}
];

/** The scripts of the listed letters (Common ones join no script's ZWNJ). */
export const JOINING_SCRIPTS: readonly string[] = ${JSON.stringify([...scripts].sort())};
`;
writeFileSync(OUT, out);
console.log(
	`${OUT}: ${merged.length} ranges, scripts ${[...scripts].join(", ")}`,
);
